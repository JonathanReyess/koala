// Scans public/videos and writes src/data/video-manifest.json: the words that have BOTH
// <word>_example1.mp4 and <word>_example2.mp4. The app only offers words in this manifest, so a
// word appears in practice as soon as its two clips are dropped into public/videos and this
// script runs (predev / prebuild / pretest / postinstall).
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = new Set(readdirSync(join(root, "public", "videos")));
const stems = new Set();
for (const f of files) {
  const m = f.match(/^(.*)_example[12]\.mp4$/);
  if (m) stems.add(m[1]);
}
const words = [...stems].filter((w) => files.has(`${w}_example1.mp4`) && files.has(`${w}_example2.mp4`)).sort();
writeFileSync(
  join(root, "src", "data", "video-manifest.json"),
  JSON.stringify({ _comment: "Generated by scripts/build-video-manifest.mjs — do not edit.", words }, null, 1) + "\n",
);
console.log(`build-video-manifest: ${words.length} words with both example clips`);
